"""Tiny authored dataset for an independent real-activation walkthrough."""
from importlib.resources import files
import json
from pathlib import Path

from .features import model_location, prompt
from .io import require_empty, sha256, write_json


def tokenizer_for(model, revision):
    from transformers import AutoConfig, AutoTokenizer
    directory, identity = model_location(model, revision)
    tokenizer = AutoTokenizer.from_pretrained(directory, local_files_only=True)
    config = AutoConfig.from_pretrained(directory, local_files_only=True)
    return tokenizer, identity, config.max_position_embeddings


def prepare_sample(out, model='Qwen/Qwen2.5-0.5B', revision=None):
    source = files('slice_probe').joinpath('sample_answers.jsonl').read_text()
    rows = [json.loads(line) for line in source.splitlines() if line.strip()]
    tokenizer, identity, context = tokenizer_for(model, revision)
    # Validate/tokenize before creating the output, so a failed download leaves no partial sample.
    batches = []
    for row in rows:
        ids = tokenizer.encode(prompt(row['question']), add_special_tokens=False)
        responses = []
        for answer in row['answers']:
            tokens = tokenizer.encode(answer['text'], add_special_tokens=False)
            if not ids or not tokens or len(ids) + len(tokens) > context:
                raise ValueError('Sample exceeds model context or tokenization is empty')
            responses.append(dict(text=answer['text'], token_ids=tokens, score=answer['score'],
                status='correct' if answer['score'] else 'incorrect', capped=False,
                label_source='authored-example'))
        batches.append(dict(id=row['id'], prompt_ids=ids, responses=responses))
    out = require_empty(out)
    write_json(out / 'questions.json', [{k: v for k, v in row.items() if k != 'answers'} for row in rows])
    (out / 'answers').mkdir()
    for i, batch in enumerate(batches):
        write_json(out / 'answers' / f'{i:05d}.json', batch)
    write_json(out / 'manifest.json', dict(format='slice-answers-v1', model=identity,
        questions_sha256=sha256(out / 'questions.json'), responses=2,
        prompt_version='completion-boxed-v1', label_source='authored-example',
        scope='Seven hand-written questions, fourteen labeled answers. Not generated by this model; '
              'not a benchmark or evidence of predicting this model’s own success.'))
    print(f'Saved 7 questions and 14 authored answers to {out}')
